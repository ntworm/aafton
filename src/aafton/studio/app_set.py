"""Read and convert steps of the app page, Live to AAF.

The read describes the set as it is: one row for every track of the scan, what
goes back to an AAF as it is and what has to become audio first. It writes
nothing. The convert writes the destination with the tracks the user chose and
says what the result was worth, never more than what was measured.
"""

