"""Relatorios do leitor de AAF.

As funcoes daqui emitem os avisos e os resumos que a leitura de um AAF produz
depois que as tracks ja foram lidas. Ficam num modulo proprio para manter o
aaf_read.py curto e cada funcao dentro dos limites do quality gate.
"""

from __future__ import annotations

from .ir import SessionIR
from .report import Report

from .aaf_read_tracks import TrackContext


def _resumir_fades(ctx: TrackContext, fades: str, report: Report) -> None:
    """Resume os fades absorvidos e os mantidos por falta de fonte."""
    if fades != "absorb":
        return
    total_absorbed_fades = ctx.total_absorbed_fades
    fades_mantidos_por_falta_de_fonte = ctx.fades_mantidos_por_falta_de_fonte
    if total_absorbed_fades > 0:
        report.info(
            "FADE_RENDER_DISCARDED",
            f"{total_absorbed_fades} rendered fade files from Pro Tools were "
            f"replaced by native Live fades; the curve generated by Live is not bit for bit "
            f"identical to the render. Use --fades keep to preserve the rendered files.",
            {"fades_absorbed": total_absorbed_fades},
        )
    if fades_mantidos_por_falta_de_fonte > 0:
        report.info(
            "FADE_KEPT_SUMMARY",
            f"{fades_mantidos_por_falta_de_fonte} fades were kept as their own clip because the file "
            f"of the previous clip had no material to cover them. The rendered audio of those spans "
            f"is kept as it is, but they do not appear as an editable fade in Live.",
            {"fades_kept": fades_mantidos_por_falta_de_fonte},
        )


def _avisar_clips_curtos(session: SessionIR, report: Report) -> None:
    """Avisa sobre clips com duracao menor que 1000 samples."""
    for track in session.tracks:
        for clip in track.clips:
            if clip.duration_samples < 1000:
                report.warning(
                    "CLIP_VERY_SHORT",
                    f"the clip {clip.name!r} in the track {track.name!r} has a duration of only "
                    f"{clip.duration_samples} samples; Live may discard very short clips",
                    {
                        "track": track.name,
                        "clip": clip.name,
                        "duration_samples": clip.duration_samples,
                    },
                )


def _avisar_pan_estatico(static_pan_count: int, report: Report) -> None:
    """Avisa quantas tracks receberam pan estatico do AAF."""
    if static_pan_count:
        report.info(
            "AAF_STATIC_PAN_IMPORTED",
            f"{static_pan_count} tracks received static pan from the AAF",
            {"count": static_pan_count},
        )


def _contar_rampas(report: Report) -> tuple[int, int]:
    """Conta as rampas de automacao de ganho por tipo de aviso."""
    clip_ramps = len([i for i in report.issues if i.code == "AAF_GAIN_AUTOMATION"])
    fade_ramps = len([i for i in report.issues if i.code == "AAF_GAIN_AUTOMATION_IN_FADE"])
    return clip_ramps, fade_ramps


def _tracks_com_envelope(session: SessionIR) -> set[str]:
    """Nomes das tracks que receberam envelope de automacao de ganho."""
    return {t.name for t in session.tracks if t.gain_points}


def _remover_avisos_de_envelope(report: Report, tracks_with_envelope: set[str]) -> None:
    """Remove os avisos de automacao das tracks que agora tem envelope."""
    report.issues[:] = [
        i
        for i in report.issues
        if not (
            i.code in ("AAF_GAIN_AUTOMATION", "AAF_GAIN_AUTOMATION_IN_FADE")
            and i.context.get("track") in tracks_with_envelope
        )
    ]


def _avisar_envelopes(session: SessionIR, report: Report) -> None:
    """Emite GAIN_ENVELOPE_WRITTEN para cada track que recebeu envelope."""
    for track in session.tracks:
        if track.gain_points:
            report.info(
                "GAIN_ENVELOPE_WRITTEN",
                f"the track {track.name!r} received a volume automation envelope with {len(track.gain_points)} points",
                {"track": track.name, "points": len(track.gain_points)},
            )


def _resumir_ganho(session: SessionIR, report: Report) -> None:
    """Resume a automacao de ganho e limpa os avisos ja convertidos em envelope."""
    clip_ramps, fade_ramps = _contar_rampas(report)
    total_ramps = clip_ramps + fade_ramps

    # Emitir GAIN_ENVELOPE_WRITTEN para tracks que receberam curva de automacao
    # e remover os avisos antigos AAF_GAIN_AUTOMATION / AAF_GAIN_AUTOMATION_IN_FADE
    # emitidos durante o processo de construcao dos raw_items para essas tracks.
    tracks_with_envelope = _tracks_com_envelope(session)

    converted_ramps = 0
    if tracks_with_envelope:
        converted_ramps = len(
            [
                i
                for i in report.issues
                if i.code in ("AAF_GAIN_AUTOMATION", "AAF_GAIN_AUTOMATION_IN_FADE")
                and i.context.get("track") in tracks_with_envelope
            ]
        )
        _remover_avisos_de_envelope(report, tracks_with_envelope)
        _avisar_envelopes(session, report)

    if total_ramps > 0:
        report.info(
            "GAIN_AUTOMATION_SUMMARY",
            f"Found {total_ramps} gain automation ramps in the AAF ({clip_ramps} in the clip body, {fade_ramps} in the fade segment, {converted_ramps} converted to an envelope)",
            {
                "total": total_ramps,
                "clip": clip_ramps,
                "fade": fade_ramps,
                "envelope_written": converted_ramps,
            },
        )


def _avisar_plugins_ignorados(report: Report) -> None:
    """Avisa quantas instancias de plugins foram ignoradas na leitura."""
    if hasattr(report, "_ignored_plugins") and report._ignored_plugins:
        count = len(report._ignored_plugins)
        report.info(
            "READ_PLUGIN",
            f"{count} plugin instances in the AAF were ignored.",
            {"count": count},
        )
